/** 이번 글의 조건 */
export function topicBlock(state: State): string {
  const d = intentDef(state.intent)
  return (
    '# 오늘의 궁금증\n' +
    '- 다룰 질문: ' + (state.topic.trim() || '[미입력]') + '\n' +
    '- 궁금증 유형: ' + d.label + ' (' + d.suffix + ')\n' +
    '- 권장 본문 뼈대: ' + d.outline + '\n' +
    '- 분야: ' + state.field + '\n' +
    '- 전제·범위: ' + (state.target.trim() || '[지정 없음 — 일반적인 조건을 가정하고 단정하지 말 것]') + '\n' +
    '- 이 질문을 검색할 사람: ' + (state.reader.trim() || '[지정 없음 — 질문에서 추론]') + '\n' +
    '- 작성자가 확인한 사실: ' + (state.facts.trim() || '[없음 — 잘 알려진 범위에서만 쓰고, 불확실한 건 checks로]') + '\n' +
    '- 목표 분량: ' + state.length + '\n'
  )
}

